/* ---- load SITE + headerHTML() exactly as the browser would ---- */
function loadHeaderTemplate() {
  const ctx = {
    document: { addEventListener() {}, querySelector() { return null; } },
    window: {}, location: { pathname: "/home.html", search: "" }, localStorage: { getItem() { return null; } },
    $id: () => null, console
  };
  vm.createContext(ctx);
  const settings = fs.readFileSync(path.join(FRONTEND, "content/site-settings.js"), "utf8");
  vm.runInContext(settings + "\n;this.SITE = SITE;", ctx);
  const navbar = fs.readFileSync(path.join(FRONTEND, "assets/js/navbar.js"), "utf8");
  vm.runInContext(navbar + "\n;this.__headerHTML = headerHTML;", ctx);
  return ctx.__headerHTML;
}

