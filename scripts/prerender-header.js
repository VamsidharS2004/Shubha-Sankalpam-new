function processPage(file, headerHTML) {
  const full = path.join(FRONTEND, file);
  let html = fs.readFileSync(full, "utf8");
  const before = html;

  // 1. shared head block
  if (html.includes("<!-- ss-head:start")) {
    html = html.replace(/<!-- ss-head:start[\s\S]*?<!-- ss-head:end -->/, HEAD_BLOCK);
  } else {
    html = html.replace(OLD_LANG_SCRIPT, "");
    html = html.replace(/<head>\s*/, m => m + HEAD_BLOCK + "\n");
  }
  html = html.replace(OLD_LANG_SCRIPT, ""); // stray copies in <body>
  for (const re of GOOGLE_FONTS) html = html.replace(re, "");
  // one shared set of tab icons (in the head block); drop any older per-page icon links
  {
    const ICONS = /[ \t]*<link rel="(?:icon|shortcut icon|apple-touch-icon)"[^>]*>[ \t]*\n?/g;
    const endMark = "<!-- ss-head:end -->", a = html.indexOf("<!-- ss-head:start"), b = html.indexOf(endMark) + endMark.length;
    html = html.slice(0, a).replace(ICONS, "") + html.slice(a, b) + html.slice(b).replace(ICONS, "");
  }

  // 1a. the puja page is served at /puja-details/001, so relative links need <base href="/"> (first thing in <head>)
  if (file === "puja-details.html" || file === "payment.html") {
    html = html.replace(/<base href="\/">\s*/g, "");
    html = html.replace(/<head>\s*/, m => m + '<base href="/">\n');
  }

  html = bakeHints(html, file);

  // 1b. search/share tags, right after the shared head block
  html = html.replace(/<!-- ss-seo:start[\s\S]*?<!-- ss-seo:end -->\n?/, "");
  html = html.replace("<!-- ss-head:end -->", m => m + "\n" + seoBlock(file, html));

  // 2. pre-rendered header
  // the inline script measures the real header height before first paint, so page content never jumps up when navbar.js measures it later
  const markup = `<div id="site-header"><!-- ss-header:start (generated from navbar.js) -->${headerHTML(file)}\n<script>(function(){var h=document.querySelector("#site-header>header");if(h)document.documentElement.style.setProperty("--header-h",h.offsetHeight+"px")})()</script>\n<!-- ss-header:end --></div>`;
  if (html.includes("<!-- ss-header:start")) {
    html = html.replace(/<div id="site-header"><!-- ss-header:start[\s\S]*?<!-- ss-header:end --><\/div>/, markup);
  } else if (/<div id="site-header"><\/div>/.test(html)) {
    html = html.replace(/<div id="site-header"><\/div>/, markup);
  } else {
    // an older hand-written static header (home.html): it ends with the mobile bottom nav
    html = html.replace(/<div id="site-header">[\s\S]*?<nav class="bottom-nav"[\s\S]*?<\/nav>\s*<\/div>/, markup);
  }

  // 2b. Telugu text baked in (see bakeTelugu)
  html = bakeTelugu(html);

  // 2c. early text script, just before </body>
  html = html.replace(/<!-- ss-early:start[\s\S]*?<!-- ss-early:end -->\n?/, "");
  html = html.replace(/<\/body>/i, m => EARLY_BLOCK + "\n" + m);

  // 3. cache-busting version for local CSS/JS
  html = html.replace(/((?:assets|content)\/[^"?]+\.(?:css|js))\?v=[^"]+"/g, `$1?v=${VERSION}"`);

  if (html !== before) fs.writeFileSync(full, html);
  return html !== before;
}

/* Baked first-visit hints: id -> Telugu title, price, muhurat and photo of every live puja (see the head script). */
function bakedPujaHints() {
  try {
    const ctx = {}; vm.createContext(ctx);
    vm.runInContext(fs.readFileSync(path.join(FRONTEND, "content/pujas.js"), "utf8") + "\n;this.__p = pujas;", ctx);
    const { state } = require("../backend/utils/pujaVisibility");
    const out = {};
    for (const p of ctx.__p || []) {
      if (p.language !== "te" || state(p) !== "live") continue;
      const t = [p.title_te, p.name_te, p.title, p.name].find(v => typeof v === "string" && v.trim());
      if (!t) continue;
      const i = typeof p.image === "string" && /^(https:\/\/|\/?assets\/)/.test(p.image) ? p.image : "";
      out[p.id] = { t, p: p.price || p.basePrice || 0, m: p.muhurat ? Date.parse(p.muhurat) || 0 : 0, i };
    }
    return out;
  } catch (_) { return {}; }
}
function bakeHints(html, file) {
  html = html.replace(/<!-- ss-baked:start[\s\S]*?<!-- ss-baked:end -->\n?/, "");
  if (file !== "puja-details.html" && file !== "booking.html") return html;
  const json = JSON.stringify(bakedPujaHints()).replace(/</g, "\\u003c");
  return html.replace("<!-- ss-head:start", () => `<!-- ss-baked:start (generated) --><script>window.__ssBaked=${json};</script><!-- ss-baked:end -->\n<!-- ss-head:start`);
}

