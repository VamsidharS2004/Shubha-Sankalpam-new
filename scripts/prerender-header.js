/* ================================================================
   PRERENDER HEADER + SHARED <head> BLOCK
   ----------------------------------------------------------------
   Run after editing the header template in frontend/assets/js/navbar.js
   (or the HEAD_BLOCK below):

       node scripts/prerender-header.js

   What it does to every public page in frontend/:
   1. Bakes the nav bar markup (from navbar.js headerHTML) straight into
      <div id="site-header">, so the header is visible on the very first
      paint instead of appearing after JavaScript loads. This is what
      stops the nav bar from blinking when moving between pages.
   2. Inserts one shared <head> block (between ss-head markers) that:
      - sets the saved language before anything paints and hides
        translatable text until it has been translated (no English flash),
      - loads self-hosted fonts (no Google Fonts round trips; font-display:fallback
 *     so cached fonts are used straight away instead of flashing a system font),
      - enables smooth same-site page transitions where supported,
      - prefetches pages when a link is hovered/pressed.
   3. Bumps ?v= on local CSS/JS so browsers pick up the new files.
   Safe to run repeatedly.
   ================================================================ */
