/* ---- search + share tags (canonical, Open Graph, Twitter, noindex for private pages) ---- */
const SITE_URL = "https://www.shubhasankalpam.com";
const PRIVATE_PAGES = new Set(["account.html", "login.html", "payment.html", "booking.html"]);
const DEFAULT_DESC = "Book authentic Vedic pujas and homams at sacred temples across India with verified purohits and video proof.";
function seoBlock(file, html) {
  if (PRIVATE_PAGES.has(file)) return `<!-- ss-seo:start -->\n<meta name="robots" content="noindex,nofollow">\n<!-- ss-seo:end -->`;
  const title = ((html.match(/<title[^>]*>([\s\S]*?)<\/title>/) || [])[1] || "Shubha Sankalpam").replace(/"/g, "&quot;").trim();
  const desc = ((html.match(/<meta name="description" content="([^"]*)"/) || [])[1] || DEFAULT_DESC);
  const url = file === "home.html" ? SITE_URL + "/" : SITE_URL + "/" + file;
  const lines = [
    file === "puja-details.html" ? "" : `<link rel="canonical" href="${url}">`,
    `<meta property="og:site_name" content="Shubha Sankalpam">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:title" content="${title}">`,
    `<meta property="og:description" content="${desc}">`,
    file === "puja-details.html" ? "" : `<meta property="og:url" content="${url}">`,
    `<meta property="og:image" content="${SITE_URL}/assets/images/logo.png">`,
    `<meta name="twitter:card" content="summary">`
  ].filter(Boolean);
  if (file === "home.html") {
    /* tells Google the site's name + alternate names (so "Shubha", "Sankalpam", "Shubha Sankalpam" all map to this site) */
    const ld = [{
      "@context": "https://schema.org", "@type": "WebSite", "name": "Shubha Sankalpam",
      "alternateName": ["Shubha Sankalpam Online Puja Booking", "Shubha Sankalpam Puja", "Shubha", "Sankalpam", "శుభ సంకల్పం"],
      "url": SITE_URL + "/", "inLanguage": ["te", "en", "hi"]
    }, {
      "@context": "https://schema.org", "@type": "Organization", "name": "Shubha Sankalpam",
      "alternateName": "శుభ సంకల్పం", "url": SITE_URL + "/", "logo": SITE_URL + "/assets/images/logo.png",
      "description": desc
    }];
    lines.push(`<script type="application/ld+json">${JSON.stringify(ld).replace(/</g, "\\u003c")}</script>`);
  }
  return `<!-- ss-seo:start (generated by scripts/prerender-header.js) -->\n${lines.join("\n")}\n<!-- ss-seo:end -->`;
}

function processPage(file, headerHTML) {
  const full = path.join(FRONTEND, file);
  let html = fs.readFileSync(full, "utf8");
  const before = html;

  // 1. shared head block
  if (html.includes("<!-- ss-head:start")) {
    html = html.replace(/<!-- ss-head:start[\s\S]*?<!-- ss-head:end -->/, HEAD_BLOCK);
  } else {
    html = html.replace(OLD_LANG_SCRIPT, "");
    html = html.replace(/<head>\s*/, m => m + HEAD_BLOCK + "\n");
  }
  html = html.replace(OLD_LANG_SCRIPT, ""); // stray copies in <body>
  for (const re of GOOGLE_FONTS) html = html.replace(re, "");
  // one shared set of tab icons (in the head block); drop any older per-page icon links
  {
    const ICONS = /[ \t]*<link rel="(?:icon|shortcut icon|apple-touch-icon)"[^>]*>[ \t]*\n?/g;
    const endMark = "<!-- ss-head:end -->", a = html.indexOf("<!-- ss-head:start"), b = html.indexOf(endMark) + endMark.length;
    html = html.slice(0, a).replace(ICONS, "") + html.slice(a, b) + html.slice(b).replace(ICONS, "");
  }

  // 1a. the puja page is served at /puja-details/001, so relative links need <base href="/"> (first thing in <head>)
  if (file === "puja-details.html") {
    html = html.replace(/<base href="\/">\s*/g, "");
    html = html.replace(/<head>\s*/, m => m + '<base href="/">\n');
  }

  // 1b. search/share tags, right after the shared head block
  html = html.replace(/<!-- ss-seo:start[\s\S]*?<!-- ss-seo:end -->\n?/, "");
  html = html.replace("<!-- ss-head:end -->", m => m + "\n" + seoBlock(file, html));

  // 2. pre-rendered header
  // the inline script measures the real header height before first paint, so page content never jumps up when navbar.js measures it later
  const markup = `<div id="site-header"><!-- ss-header:start (generated from navbar.js) -->${headerHTML(file)}\n<script>(function(){var h=document.querySelector("#site-header>header");if(h)document.documentElement.style.setProperty("--header-h",h.offsetHeight+"px")})()</script>\n<!-- ss-header:end --></div>`;
  if (html.includes("<!-- ss-header:start")) {
    html = html.replace(/<div id="site-header"><!-- ss-header:start[\s\S]*?<!-- ss-header:end --><\/div>/, markup);
  } else if (/<div id="site-header"><\/div>/.test(html)) {
    html = html.replace(/<div id="site-header"><\/div>/, markup);
  } else {
    // an older hand-written static header (home.html): it ends with the mobile bottom nav
    html = html.replace(/<div id="site-header">[\s\S]*?<nav class="bottom-nav"[\s\S]*?<\/nav>\s*<\/div>/, markup);
  }

  // 3. cache-busting version for local CSS/JS
  html = html.replace(/((?:assets|content)\/[^"?]+\.(?:css|js))\?v=[^"]+"/g, `$1?v=${VERSION}"`);

  if (html !== before) fs.writeFileSync(full, html);
  return html !== before;
}

const headerHTML = loadHeaderTemplate();
const pages = fs.readdirSync(FRONTEND).filter(f => f.endsWith(".html") && !SKIP.has(f));
for (const file of pages) {
  const changed = processPage(file, headerHTML);
  console.log((changed ? "updated  " : "unchanged") + "  " + file);
}

